def question(prompt: str, options: list[str], correct: int) -> dict:
    return {
        "prompt": prompt,
        "options": [{"body": body, "isCorrect": index == correct} for index, body in enumerate(options)],
    }


def block(theory: str, questions: list[dict]) -> dict:
    return {"theory": theory, "questions": questions}


