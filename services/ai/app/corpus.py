def niches_for(hobbies: list[str]) -> list[str]:
    found = []
    for hobby in hobbies:
        label = HOBBY_NICHE.get(str(hobby))
        if label and label not in found:
            found.append(label)
    return found or ["малый городской бизнес"]


def niche_phrase(niches: list[str]) -> str:
    if len(niches) == 1:
        return niches[0]
    return ", ".join(niches[:-1]) + " и " + niches[-1]


def niche_for(hobbies: list[str]) -> str:
    return niche_phrase(niches_for(hobbies))


def block_material(discipline_title: str, slot_title: str) -> dict | None:
    number = _block_number(slot_title)
    found = BLOCKS.get((discipline_title, number))
    if found is None:
        return None
    return {"theoryMarkdown": found["theory"], "questions": found["questions"]}


def boss_material(module_title: str) -> dict | None:
    found = BOSSES.get(module_title)
    if found is None:
        return None
    return {"promptMarkdown": found["prompt"]}


def boss_case(prompt: str) -> dict | None:
    for case in BOSSES.values():
        if case["prompt"] == prompt:
            return case
    return None


def _spread_answers() -> None:
    for item in BLOCKS.values():
        for quiz in item["questions"]:
            options = quiz["options"]
            shift = sum(ord(char) for char in quiz["prompt"]) % len(options)
            if shift:
                quiz["options"] = options[shift:] + options[:shift]


_spread_answers()


def _block_number(slot_title: str) -> int:
    marker = ", блок "
    if marker not in slot_title:
        return 1
    tail = slot_title.rsplit(marker, 1)[1].strip()
    digits = []
    for char in tail:
        if char.isdigit():
            digits.append(char)
        else:
            break
    if not digits:
        return 1
    return int("".join(digits))
